@app.route("/predict", methods=["POST"])
def predict():

    data = request.json

    values = [[
        data["bedrooms"],
        data["bathrooms"],
        data["sqft_living"],
        data["sqft_lot"],
        data["floors"],
        data["waterfront"],
        data["view"],
        data["condition"],
        data["sqft_above"],
        data["sqft_basement"],
        data["yr_built"],
        data["yr_renovated"]
    ]]

    columns = [
        "bedrooms",
        "bathrooms",
        "sqft_living",
        "sqft_lot",
        "floors",
        "waterfront",
        "view",
        "condition",
        "sqft_above",
        "sqft_basement",
        "yr_built",
        "yr_renovated"
    ]

    df = pd.DataFrame(values, columns=columns)

    prediction = model.predict(df)[0]

    # Save prediction in MySQL
    sql = """
    INSERT INTO prediction_history(
        bedrooms,
        bathrooms,
        sqft_living,
        sqft_lot,
        floors,
        waterfront,
        view,
        `condition`,
        sqft_above,
        sqft_basement,
        yr_built,
        yr_renovated,
        predicted_price
    )
    VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)
    """

    record = (
        data["bedrooms"],
        data["bathrooms"],
        data["sqft_living"],
        data["sqft_lot"],
        data["floors"],
        data["waterfront"],
        data["view"],
        data["condition"],
        data["sqft_above"],
        data["sqft_basement"],
        data["yr_built"],
        data["yr_renovated"],
        float(prediction)
    )

    cursor.execute(sql, record)
    db.commit()

    return jsonify({
        "Predicted Price": float(prediction)
    })


