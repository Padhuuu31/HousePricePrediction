@app.route("/history")
def history():

    cursor.execute("SELECT * FROM prediction_history ORDER BY id DESC")

    rows = cursor.fetchall()

    return render_template("history.html", rows=rows)

@app.route("/dashboard")
def dashboard():

    cursor.execute("SELECT COUNT(*) FROM prediction_history")
    total = cursor.fetchone()[0]

    cursor.execute("SELECT AVG(predicted_price) FROM prediction_history")
    avg_price = cursor.fetchone()[0] or 0

    cursor.execute("SELECT MAX(predicted_price) FROM prediction_history")
    max_price = cursor.fetchone()[0] or 0

    cursor.execute("SELECT MIN(predicted_price) FROM prediction_history")
    min_price = cursor.fetchone()[0] or 0

    cursor.execute("SELECT id,predicted_price FROM prediction_history ORDER BY id")

    rows = cursor.fetchall()

    labels = [row[0] for row in rows]
    prices = [float(row[1]) for row in rows]

    return render_template(
        "dashboard.html",
        total=total,
        avg_price=avg_price,
        max_price=max_price,
        min_price=min_price,
        labels=labels,
        prices=prices
    )

