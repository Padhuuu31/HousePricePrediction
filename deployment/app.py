@app.route("/download_report", methods=["POST"])
def download_report():

    data = request.json

    temp_file = tempfile.NamedTemporaryFile(
        delete=False,
        suffix=".pdf"
    )

    doc = SimpleDocTemplate(temp_file.name)

    styles = getSampleStyleSheet()

    story = []

    story.append(
        Paragraph(
            "<b><font size=18>House Price Prediction Report</font></b>",
            styles["Title"]
        )
    )

    story.append(Paragraph("<br/>", styles["Normal"]))

    story.append(
        Paragraph(
            f"<b>Predicted Price:</b> ₹ {data['predicted_price']:,.2f}",
            styles["BodyText"]
        )
    )

    story.append(Paragraph("<br/>", styles["Normal"]))

    story.append(
        Paragraph("<b>Property Details</b>", styles["Heading2"])
    )

    story.append(
        Paragraph(
            f"Bedrooms : {data['bedrooms']}",
            styles["BodyText"]
        )
    )

    story.append(
        Paragraph(
            f"Bathrooms : {data['bathrooms']}",
            styles["BodyText"]
        )
    )

    story.append(
        Paragraph(
            f"Living Area : {data['sqft_living']} sqft",
            styles["BodyText"]
        )
    )

    story.append(
        Paragraph(
            f"Lot Area : {data['sqft_lot']} sqft",
            styles["BodyText"]
        )
    )

    story.append(
        Paragraph(
            f"Floors : {data['floors']}",
            styles["BodyText"]
        )
    )

    story.append(
        Paragraph(
            f"Year Built : {data['yr_built']}",
            styles["BodyText"]
        )
    )

    story.append(Paragraph("<br/>", styles["Normal"]))

    story.append(
        Paragraph(
            "Generated by House Price Prediction System",
            styles["Italic"]
        )
    )

    doc.build(story)

    return send_file(
        temp_file.name,
        as_attachment=True,
        download_name="House_Price_Prediction_Report.pdf"
    )


